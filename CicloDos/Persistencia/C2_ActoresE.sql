    PROCEDURE AD_RESOLUCION (xId_Incidencia IN NUMBER, xFechas_Suspension IN NUMBER, xMulta_Monto IN NUMBER, xDescripcion IN VARCHAR2);
    PROCEDURE MOD_RESOLUCION (xId_Resolucion IN NUMBER, xFechas_Suspension IN NUMBER, xMulta_Monto IN NUMBER, xDescripcion IN VARCHAR2);
    PROCEDURE EL_RESOLUCION (xId_Resolucion IN NUMBER);

    -- Manuales y Bloqueados de PK_INCIDENCIA
    PROCEDURE MOD_INCIDENCIA (xId_Incidencia IN NUMBER, xMinuto IN NUMBER, xTipo IN VARCHAR2);
    PROCEDURE EL_INCIDENCIA (xId_Incidencia IN NUMBER);
    
    -- Manuales y Bloqueados de PK_ESTADISTICA_JUGADOR
    PROCEDURE AD_ESTADISTICA_JUGADOR (xId_Jugador IN NUMBER, xId_Torneo IN NUMBER);
    PROCEDURE MOD_ESTADISTICA_JUGADOR (xId_Estadistica IN NUMBER, xGoles IN NUMBER, xAsistencias IN NUMBER, xTarjetas_Amarillas IN NUMBER, xTarjetas_Rojas IN NUMBER, xPartidos_Jugados IN NUMBER);
    PROCEDURE EL_ESTADISTICA_JUGADOR (xId_Estadistica IN NUMBER);
END PA_ADMINISTRADOR_C2;

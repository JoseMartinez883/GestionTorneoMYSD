    PROCEDURE AD_TARIFA (xConcepto IN VARCHAR2, xValor IN NUMBER);
    PROCEDURE MOD_TARIFA (xId_Tarifa IN NUMBER, xConcepto IN VARCHAR2, xValor IN NUMBER);
